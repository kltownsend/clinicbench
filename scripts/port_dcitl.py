"""Generate the F adapter's driver from Lab 23's frozen driver, by listed substitutions only.

The original (pb/dcitl.py, sha256 2dce94bd...) is vendored as
clinicbench/adapters/lab23_dcitl.py.orig. This script applies the substitutions below and writes
clinicbench/adapters/dcitl_port.py. tests/test_adapter.py reruns it and checks the committed
port is exactly its output, so the driver's parsers, consent rule and escalation rule are
provably the frozen ones.

usage: python scripts/port_dcitl.py [--check]
"""

from __future__ import annotations

import hashlib
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "clinicbench", "adapters")
ORIG = os.path.join(ROOT, "lab23_dcitl.py.orig")
OUT = os.path.join(ROOT, "dcitl_port.py")
ORIG_SHA = "2dce94bdc85b0f148ca149c31c1009d5dc815b01f226afcc8505aa79f85fe42b"

HEADER = '''# GENERATED by scripts/port_dcitl.py from Lab 23's frozen driver (pb/dcitl.py, sha256
# 2dce94bdc85b0f14...). Do not edit; edit the substitutions in the script instead.
# Substitutions, and nothing else:
#   1. the kit's `services` module -> a shim over the bench's tool API, passed in per session
#      (self.svc); module-level provider lookups read the clinic's static directory
#   2. the kit ledger's turn counter (L.LEDGER.turn) -> the model's own turn attribute
#   3. Lab 23's scripted-session loop (run_dcitl) removed; the bench's adapter drives the session
'''

SUBS = [
    ("from clinic import services\n\nfrom pb import ledger as L\n", "from .shim import DIRECTORY\n"),
    ("    st, t = services.store, u.lower()", "    st, t = DIRECTORY, u.lower()"),
    ("        self.log: list[dict] = []\n", "        self.log: list[dict] = []\n        self.turn = 0\n"),
    ('self.log.append({"turn": L.LEDGER.turn, "kind": kind,', 'self.log.append({"turn": self.turn, "kind": kind,'),
    ('self.log.append({"turn": L.LEDGER.turn, "kind": "identity_extract",',
     'self.log.append({"turn": self.turn, "kind": "identity_extract",'),
    ("    def __init__(self, model: Model, consent_in_code: bool = False):\n        self.m = model\n",
     "    def __init__(self, model: Model, svc, consent_in_code: bool = False):\n        self.m = model\n"
     "        self.svc = svc\n"),
    ("        self.st = services.store\n", "        self.st = svc.store\n"),
    ('self.human_queue.append({"turn": L.LEDGER.turn,', 'self.human_queue.append({"turn": self.m.turn,'),
    ("services.registry.", "self.svc.registry."),
    ("services.eligibility.", "self.svc.eligibility."),
    ("services.schedule.", "self.svc.schedule."),
]


def port() -> str:
    src = open(ORIG).read()
    assert hashlib.sha256(src.encode()).hexdigest() == ORIG_SHA, "vendored original changed"
    src = src[:src.index("\ndef run_dcitl(")] + "\n"
    for old, new in SUBS:
        n = src.count(old)
        assert n >= 1, f"substitution not found: {old[:50]!r}"
        src = src.replace(old, new)
    assert "services." not in src.replace("self.svc.", "") and "L.LEDGER" not in src
    return HEADER + src


if __name__ == "__main__":
    out = port()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT).read() == out else 1)
    open(OUT, "w").write(out)
    print("wrote", OUT)
